# numeros.py
# Exemplos de números e operações aritméticas em Python

# Números inteiros
a = 10
b = 3

# Números de ponto flutuante
x = 7.5
y = 2.0

# Operações aritméticas básicas
soma = a + b
subtracao = a - b
multiplicacao = a * b
divisao = a / b
divisao_inteira = a // b
resto = a % b
potencia = a ** b

# Operações com floats
soma_float = x + y
divisao_float = x / y

print("Soma:", soma)
print("Subtração:", subtracao)
print("Multiplicação:", multiplicacao)
print("Divisão:", divisao)
print("Divisão inteira:", divisao_inteira)
print("Resto da divisão:", resto)
print("Potência:", potencia)
print("Soma (float):", soma_float)
print("Divisão (float):", divisao_float)